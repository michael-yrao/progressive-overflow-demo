# The caveat appended to the NeetCode mirror URL's NOTE when NeetCode's own list cannot
# confirm the slug (an unread/unreadable neetcode.yml, and the slug isn't even a known
# NEETCODE_RENAMES entry) — NeetCode's site answers 200 for any slug, so this is the only
# honest signal left that the link might be dead.
NEETCODE_UNVERIFIED_CAVEAT = " (slug unverified — NeetCode has no API)"


def load_hellointerview_map() -> dict[str, str]:
    """{leetcode_slug: HelloInterview path} from `hellointerview.yml`.

    Fail-soft, same style as `gamify.py`'s `load_roadmap()`/`load_technique_entries()`: a
    missing file, missing PyYAML, or unparsable YAML degrades to `{}` with one printed
    NOTE rather than raising — a scaffold must not depend on this file existing. A
    malformed individual entry (no `leetcode_slug` or no `path`) is silently skipped
    rather than crashing the whole load.
    """
    try:
        import yaml  # noqa: PLC0415
        config = yaml.safe_load(HELLOINTERVIEW_MAP_PATH.read_text(encoding="utf-8")) or {}
    except Exception:  # noqa: BLE001 — a missing/unparsable file is a normal fail-soft state
        print("NOTE: hellointerview.yml not readable — HelloInterview is skipped when "
              "choosing a link for a premium problem.")
        return {}
    return {
        entry["leetcode_slug"]: entry["path"]
        for entry in config.get("problems") or []
        if isinstance(entry, dict) and entry.get("leetcode_slug") and entry.get("path")
    }


def load_neetcode_slugs() -> frozenset[str] | None:
    """LeetCode slugs NeetCode's own public problem list carries, from `neetcode.yml`.

    Returns `None` — UNKNOWN, never "NeetCode carries nothing" — when the file is
    missing, unreadable, or PyYAML itself is missing, with one printed NOTE; a readable
    file with no matching entries returns an EMPTY frozenset instead, and the two must
    stay distinguishable (`resolve_premium_link` treats them differently — see there). A
    malformed individual entry (no `leetcode_slug`) is silently skipped rather than
    failing the whole load, same fail-soft style as `load_hellointerview_map()`.
    """
    try:
        import yaml  # noqa: PLC0415
        config = yaml.safe_load(NEETCODE_MAP_PATH.read_text(encoding="utf-8")) or {}
    except Exception:  # noqa: BLE001 — a missing/unparsable file is a normal fail-soft state
        print("NOTE: neetcode.yml not readable — premium problems fall back to the free "
              "NeetCode mirror (unverified).")
        return None
    return frozenset(
        entry["leetcode_slug"]
        for entry in config.get("problems") or []
        if isinstance(entry, dict) and entry.get("leetcode_slug")
    )


class PremiumLink(NamedTuple):
    """The one thing `resolve_premium_link` decides for a LeetCode-premium problem:
    the `url` to link, which `judge` it came from, and the plain-words `reason` clause
    for the printed NOTE — bundled so the URL and its stated reason can never disagree.

    `reason` is written to slot straight after "is premium" in the NOTE sentence at both
    call sites (`f"...is premium{reason}."`), so its own leading punctuation/connector is
    part of the string.
    """
    url: str
    judge: str
    reason: str


def resolve_premium_link(
    number: str,
    slug: str,
    neetcode_slugs: frozenset[str] | None,
    hi_map: dict[str, str],
) -> PremiumLink:
    """The link (and why) for a LeetCode-premium problem: NeetCode when its own list
    carries `slug`, else HelloInterview when `hi_map` (the crawled catalog) does, else
    the site's practice page for `number`. The one place `problem-link-order-sep27` (as
    extended by `problem-link-order-oct04`) is decided.

    `neetcode_slugs is None` means the list is UNKNOWN (unreadable), not empty — that
    must not silently fall through to HelloInterview or the site's practice page, since
    an unreadable list says nothing about whether NeetCode actually carries the problem.
    It keeps the pre-neetcode.yml fallback instead: the NeetCode mirror URL, with the
    same "unverified slug" caveat that fallback has always carried.
    """
    def neetcode_url() -> str:
        return f"https://neetcode.io/problems/{NEETCODE_RENAMES.get(slug, slug)}"

    if neetcode_slugs is None:
        caveat = "" if slug in NEETCODE_RENAMES else NEETCODE_UNVERIFIED_CAVEAT
        return PremiumLink(
            neetcode_url(), "NeetCode",
            f"; linking the free NeetCode mirror instead{caveat}",
        )
    if slug in neetcode_slugs:
        return PremiumLink(
            neetcode_url(), "NeetCode",
            "; linking NeetCode (free, in its problem list)",
        )
    if slug in hi_map:
        return PremiumLink(
            f"{HELLOINTERVIEW_HOST}{hi_map[slug]}", "HelloInterview",
            "; linking HelloInterview (NeetCode does not list it; HelloInterview's "
            "catalog does)",
        )
    return PremiumLink(
        SITE_PRACTICE_URL_TEMPLATE.format(number=number), SITE_LABEL,
        " and neither NeetCode nor HelloInterview has it; linking the PO (progressiveoverflow) "
        "practice page (needs a spec in dsa/tests)",
    )

